"""Local retrieval-augmented generation utilities for CyberSaathi.

Embeddings are generated by a local Ollama server. Vectors and source metadata
are stored in Qdrant's embedded/local mode; no hosted vector service is used.
"""
from __future__ import annotations

import asyncio
import hashlib
import logging
import re
import uuid
from functools import lru_cache
from pathlib import Path
from typing import Any

import httpx
from qdrant_client import QdrantClient, models

from app.config import settings

logger = logging.getLogger(__name__)

BACKEND_DIR = Path(__file__).resolve().parents[2]
DEFAULT_DB_PATH = BACKEND_DIR / "data" / "qdrant"


def _db_path() -> Path:
    raw = Path(settings.rag_db_path)
    return raw if raw.is_absolute() else (BACKEND_DIR / raw).resolve()


@lru_cache(maxsize=1)
def get_qdrant() -> QdrantClient:
    path = _db_path()
    path.mkdir(parents=True, exist_ok=True)
    return QdrantClient(path=str(path))


async def embed_texts(texts: list[str]) -> list[list[float]]:
    """Create embeddings locally through Ollama's /api/embed endpoint."""
    if not texts:
        return []
    url = settings.ollama_base_url.rstrip("/") + "/api/embed"
    async with httpx.AsyncClient(timeout=settings.rag_embedding_timeout_seconds) as client:
        response = await client.post(
            url,
            json={"model": settings.rag_embedding_model, "input": texts},
        )
        response.raise_for_status()
        data = response.json()
    vectors = data.get("embeddings")
    if not isinstance(vectors, list) or len(vectors) != len(texts):
        raise RuntimeError("Ollama returned an unexpected embedding response.")
    return vectors


async def embed_with_retry(texts: list[str], attempts: int = 3) -> list[list[float]]:
    """embed_texts with a few retries; a slow CPU can time out once and succeed on the next try."""
    last: Exception | None = None
    for attempt in range(1, attempts + 1):
        try:
            return await embed_texts(texts)
        except httpx.TimeoutException as exc:
            last = exc
            print(f"[INGEST] Ollama timed out after {settings.rag_embedding_timeout_seconds}s (attempt {attempt}/{attempts}).")
            await asyncio.sleep(2 * attempt)
    raise RuntimeError(
        "Ollama embedding kept timing out. Close other heavy programs (and the backend server while ingesting), "
        "then raise RAG_EMBEDDING_TIMEOUT_SECONDS or lower RAG_EMBEDDING_BATCH_SIZE in backend/.env."
    ) from last


def chunk_text(text: str, chunk_words: int = 420, overlap_words: int = 60) -> list[str]:
    """Split text into overlapping word windows while preserving readable text."""
    clean = re.sub(r"\s+", " ", text).strip()
    words = clean.split(" ") if clean else []
    if not words:
        return []
    if overlap_words >= chunk_words:
        raise ValueError("overlap_words must be smaller than chunk_words")
    chunks: list[str] = []
    step = chunk_words - overlap_words
    for start in range(0, len(words), step):
        part = " ".join(words[start:start + chunk_words]).strip()
        if part:
            chunks.append(part)
        if start + chunk_words >= len(words):
            break
    return chunks


def ensure_collection(vector_size: int) -> None:
    client = get_qdrant()
    name = settings.rag_collection
    if client.collection_exists(name):
        info = client.get_collection(name)
        current_size = info.config.params.vectors.size
        if current_size != vector_size:
            raise RuntimeError(
                f"Qdrant collection '{name}' has vector size {current_size}; "
                f"the current embedding model returned {vector_size}. Use a new collection name or re-index."
            )
        return
    client.create_collection(
        collection_name=name,
        vectors_config=models.VectorParams(size=vector_size, distance=models.Distance.COSINE),
    )


def _stable_id(source_id: str, chunk_index: int, text: str) -> str:
    digest = hashlib.sha256(f"{source_id}:{chunk_index}:{text}".encode("utf-8")).hexdigest()
    return str(uuid.UUID(digest[:32]))


async def index_documents(documents: list[dict[str, Any]]) -> dict[str, int]:
    """Embed and upsert document chunks. Each item needs text and source metadata."""
    prepared: list[dict[str, Any]] = []
    for doc in documents:
        chunks = chunk_text(str(doc.get("text", "")))
        for index, chunk in enumerate(chunks):
            prepared.append({
                "text": chunk,
                "source_id": str(doc.get("source_id") or doc.get("source") or "unknown"),
                "source": str(doc.get("source") or doc.get("source_id") or "Unknown source"),
                "url": str(doc.get("url") or ""),
                "topic": str(doc.get("topic") or "general"),
                "published": str(doc.get("published") or ""),
                "chunk_index": index,
            })
    if not prepared:
        return {"documents": len(documents), "chunks": 0}

    batch_size = max(1, int(settings.rag_embedding_batch_size))
    client = get_qdrant()

    # 1) Embed EVERYTHING first. If this fails (timeout, Ollama stopped), the existing index is left untouched.
    vectors_all: list[list[float]] = []
    for start in range(0, len(prepared), batch_size):
        batch = prepared[start:start + batch_size]
        vectors_all.extend(await embed_with_retry([item["text"] for item in batch]))
        print(f"[INGEST] embedded {len(vectors_all)}/{len(prepared)} chunks", flush=True)

    # 2) Only now replace the old chunks of these sources, then store the new ones.
    ensure_collection(len(vectors_all[0]))
    for source_id in {item["source_id"] for item in prepared}:
        client.delete(
            collection_name=settings.rag_collection,
            points_selector=models.FilterSelector(
                filter=models.Filter(
                    must=[models.FieldCondition(key="source_id", match=models.MatchValue(value=source_id))]
                )
            ),
            wait=True,
        )
    indexed = 0
    for start in range(0, len(prepared), 64):
        points = []
        for item, vector in zip(prepared[start:start + 64], vectors_all[start:start + 64]):
            point_id = _stable_id(item["source_id"], item["chunk_index"], item["text"])
            points.append(models.PointStruct(id=point_id, vector=vector, payload=dict(item)))
        client.upsert(collection_name=settings.rag_collection, points=points, wait=True)
        indexed += len(points)
    return {"documents": len(documents), "chunks": indexed}


async def retrieve_context(query: str, limit: int | None = None) -> list[dict[str, Any]]:
    """Retrieve the most similar knowledge chunks for a user incident."""
    if not settings.rag_enabled or not query.strip():
        return []
    client = get_qdrant()
    exists = await asyncio.to_thread(client.collection_exists, settings.rag_collection)
    if not exists:
        return []
    vector = (await embed_texts([query]))[0]
    result = await asyncio.to_thread(
        client.query_points,
        collection_name=settings.rag_collection,
        query=vector,
        limit=limit or settings.rag_top_k,
        with_payload=True,
        score_threshold=settings.rag_score_threshold,
    )
    matches: list[dict[str, Any]] = []
    for point in result.points:
        payload = point.payload or {}
        matches.append({
            "text": payload.get("text", ""),
            "source": payload.get("source", "Unknown source"),
            "url": payload.get("url", ""),
            "topic": payload.get("topic", "general"),
            "published": payload.get("published", ""),
            "score": float(point.score or 0.0),
        })
    return matches


def format_context(matches: list[dict[str, Any]]) -> str:
    if not matches:
        return "No relevant local knowledge-base passages were retrieved. Do not pretend that retrieval occurred."
    blocks = []
    for index, item in enumerate(matches, 1):
        blocks.append(
            f"[SOURCE {index}] {item['source']}\n"
            f"URL: {item['url'] or 'Not provided'}\n"
            f"Topic: {item['topic']} | Published/reviewed: {item['published'] or 'Not specified'}\n"
            f"Passage: {item['text']}"
        )
    return "\n\n".join(blocks)


def collection_status() -> dict[str, Any]:
    client = get_qdrant()
    exists = client.collection_exists(settings.rag_collection)
    count = client.count(settings.rag_collection, exact=True).count if exists else 0
    return {
        "enabled": settings.rag_enabled,
        "collection": settings.rag_collection,
        "indexed_chunks": count,
        "embedding_model": settings.rag_embedding_model,
        "embedding_runtime": "local Ollama",
        "vector_database": "local Qdrant",
        "collection_ready": exists and count > 0,
    }
